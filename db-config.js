let supabaseClient = null;

function initWolffiaSupabase() {
  if (typeof supabase !== 'undefined' && WOLFFIA_SUPABASE_CONFIG.url && WOLFFIA_SUPABASE_CONFIG.anonKey) {
    try {
      supabaseClient = supabase.createClient(WOLFFIA_SUPABASE_CONFIG.url, WOLFFIA_SUPABASE_CONFIG.anonKey);
      window.supabaseClient = supabaseClient;
      console.log('Supabase client initialized for Smart Wolffia IoT telemetry');
      return supabaseClient;
    } catch (e) {
      console.warn('Failed to initialize Supabase client:', e);
    }
  }
  return null;
}

