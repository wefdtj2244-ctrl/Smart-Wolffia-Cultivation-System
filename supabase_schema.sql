-- 1. สร้างตาราง sensor_readings สำหรับโค้ดบอร์ด ESP32 V6
CREATE TABLE IF NOT EXISTS public.sensor_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    device_id TEXT DEFAULT 'ESP32-WOLFFIA-01' NOT NULL,
    temperature NUMERIC(5, 2),            -- อุณหภูมิน้ำ (°C) DS18B20
    ph NUMERIC(4, 2),                     -- ค่าความเป็นกรด-ด่าง pH
    light NUMERIC(8, 2),                  -- ความเข้มแสง (Lux) BH1750
    water_level NUMERIC(5, 1),            -- ระดับน้ำ (%) Ultrasonic
    pump_status BOOLEAN DEFAULT false,    -- สถานะปั๊มน้ำ (true = ON, false = OFF)
    system_mode TEXT DEFAULT 'AUTO',      -- โหมดระบบ ('AUTO' / 'MANUAL')
    system_status TEXT DEFAULT 'NORMAL'   -- สถานะความปลอดภัย ('NORMAL' / 'EMERGENCY_STOP' / 'SENSOR_WARNING')
);

-- สร้างตาราง wolffia_telemetry สำหรับโครงสร้างเดิม (Backward Compatibility)
CREATE TABLE IF NOT EXISTS public.wolffia_telemetry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    device_id TEXT DEFAULT 'ESP32-WOLFFIA-01' NOT NULL,
    temperature NUMERIC(5, 2) NOT NULL,
    ph NUMERIC(4, 2) NOT NULL,
    water_level NUMERIC(5, 1) NOT NULL,
    light NUMERIC(6, 1) NOT NULL,
    rssi INTEGER DEFAULT -58,
    device_status TEXT DEFAULT 'Online'
);

-- 2. สร้าง Index สำหรับการ Query เรียงตามเวลา
CREATE INDEX IF NOT EXISTS idx_sensor_readings_created_at 
ON public.sensor_readings (created_at DESC);

CREATE INDEX IF NOT EXISTS idx_wolffia_telemetry_created_at 
ON public.wolffia_telemetry (created_at DESC);

-- 3. เปิดใช้งาน Supabase Realtime Stream (WebSocket) สำหรับทั้งสองตาราง
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' 
    AND schemaname = 'public' 
    AND tablename = 'sensor_readings'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.sensor_readings;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' 
    AND schemaname = 'public' 
    AND tablename = 'wolffia_telemetry'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.wolffia_telemetry;
  END IF;
END $$;

-- 4. ปลดล็อก RLS (Row Level Security) สำหรับ IoT Telemetry
-- สำคัญมาก: เพื่อป้องกัน HTTP 401 Unauthorized ที่ทำให้บอร์ด ESP32 ยิงข้อมูลไม่เข้า
ALTER TABLE public.sensor_readings DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.wolffia_telemetry DISABLE ROW LEVEL SECURITY;

-- มอบสิทธิ์การอ่านและบันทึกข้อมูล (SELECT / INSERT) ให้ Anonymous Key ของ ESP32 และเว็บ
GRANT ALL ON TABLE public.sensor_readings TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.wolffia_telemetry TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

