-- 1. สร้างตารางบันทึกค่าโทรมาตรจากเซนเซอร์ IoT (Telemetry Table)
CREATE TABLE IF NOT EXISTS public.wolffia_telemetry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    device_id TEXT DEFAULT 'ESP32-WOLFFIA-01' NOT NULL,
    temperature NUMERIC(5, 2) NOT NULL,   -- อุณหภูมิน้ำ (°C) จาก DS18B20
    ph NUMERIC(4, 2) NOT NULL,            -- ค่าความเป็นกรด-ด่าง pH จาก pH Sensor
    water_level NUMERIC(5, 1) NOT NULL,   -- ระดับน้ำ (%) จาก Ultrasonic / Liquid Level Sensor
    light NUMERIC(6, 1) NOT NULL,         -- ความเข้มแสง (Lux) จาก BH1750 / LDR
    rssi INTEGER DEFAULT -58,             -- สัญญาณ WiFi (dBm)
    device_status TEXT DEFAULT 'Online'   -- สถานะอุปกรณ์ ('Online' / 'Warning')
);

-- 2. สร้าง Index สำหรับการ Query ข้อมูลตามเวลาได้อย่างรวดเร็ว
CREATE INDEX IF NOT EXISTS idx_wolffia_telemetry_created_at 
ON public.wolffia_telemetry (created_at DESC);

-- 3. เปิดใช้งาน Supabase Realtime (WebSocket Streaming ไปยัง Dashboard)
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' 
    AND schemaname = 'public' 
    AND tablename = 'wolffia_telemetry'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.wolffia_telemetry;
  END IF;
END $$;

-- 4. มอบสิทธิ์การอ่านและบันทึกข้อมูล (SELECT / INSERT) ให้ ESP32 และ Web Dashboard
GRANT ALL ON TABLE public.wolffia_telemetry TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

-- 5. ปลดล็อก Row Level Security (RLS) สำหรับตาราง IoT Telemetry 
-- (วิธีที่เสถียรที่สุดสำหรับ IoT: ปิด RLS เพื่อให้บอร์ด ESP32 ยิงส่งข้อมูลได้ 100% ไม่ติดบล็อก)
ALTER TABLE public.wolffia_telemetry DISABLE ROW LEVEL SECURITY;

