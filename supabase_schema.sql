-- 0. ลบตารางโครงสร้างเดิมออกก่อน เพื่อป้องกัน Error คอลัมน์ไม่ตรงกัน (Column does not exist)
DROP TABLE IF EXISTS public.sensor_readings CASCADE;
DROP TABLE IF EXISTS public.wolffia_telemetry CASCADE;

-- 1. สร้างตาราง sensor_readings (ตารางหลักที่บอร์ด ESP32 V6 ส่งค่าเข้ามา)
CREATE TABLE public.sensor_readings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    device_id TEXT DEFAULT 'ESP32-WOLFFIA-01' NOT NULL,
    temperature NUMERIC(5, 2),            -- อุณหภูมิน้ำ (°C) จาก DS18B20
    ph NUMERIC(4, 2),                     -- ค่าความเป็นกรด-ด่าง pH
    light NUMERIC(8, 2),                  -- ความเข้มแสง (Lux / %) จาก BH1750
    water_level NUMERIC(5, 1),            -- ระดับน้ำในถัง (%) จาก Ultrasonic
    pump_status BOOLEAN DEFAULT false,    -- สถานะปั๊มน้ำ (true = ON, false = OFF)
    system_mode TEXT DEFAULT 'AUTO',      -- โหมดการทำงาน ('AUTO' / 'MANUAL')
    system_status TEXT DEFAULT 'NORMAL',  -- สถานะระบบ ('NORMAL' / 'EMERGENCY_STOP' / 'SENSOR_WARNING')
    rssi INTEGER DEFAULT -58,             -- ความแรงสัญญาณ Wi-Fi (dBm)
    wifi_ssid TEXT DEFAULT 'Home 96_2.4G' -- ชื่อ Wi-Fi
);

-- 2. สร้างตาราง wolffia_telemetry (ตารางสำรอง สำหรับโครงสร้างเดิม)
CREATE TABLE public.wolffia_telemetry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    device_id TEXT DEFAULT 'ESP32-WOLFFIA-01' NOT NULL,
    temperature NUMERIC(5, 2),
    ph NUMERIC(4, 2),
    water_level NUMERIC(5, 1),
    light NUMERIC(8, 2),
    rssi INTEGER DEFAULT -58,
    device_status TEXT DEFAULT 'Online'
);

-- 3. สร้าง Index เพื่อให้การดึงข้อมูลล่าสุด (Order by created_at DESC) รวดเร็วที่สุด
CREATE INDEX idx_sensor_readings_created_at ON public.sensor_readings (created_at DESC);
CREATE INDEX idx_wolffia_telemetry_created_at ON public.wolffia_telemetry (created_at DESC);

-- 4. เปิดใช้งาน Supabase Realtime Stream (WebSocket) ให้ทั้งสองตาราง
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' 
    AND schemaname = 'public' 
    AND tablename = 'sensor_readings'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.sensor_readings;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM pg_publication_tables 
    WHERE pubname = 'supabase_realtime' 
    AND schemaname = 'public' 
    AND tablename = 'wolffia_telemetry'
  ) THEN
    ALTER PUBLICATION supabase_realtime ADD TABLE public.wolffia_telemetry;
  END IF;
END $$;

-- 5. ปลดล็อก Row Level Security (RLS) เพื่อให้อุปกรณ์ IoT และเว็บเชื่อมต่อได้โดยตรง
ALTER TABLE public.sensor_readings DISABLE ROW LEVEL SECURITY;
ALTER TABLE public.wolffia_telemetry DISABLE ROW LEVEL SECURITY;

-- 6. มอบสิทธิ์การอ่าน/เขียน (SELECT, INSERT, UPDATE, DELETE) ให้กับ anon, authenticated, service_role
GRANT ALL ON TABLE public.sensor_readings TO anon, authenticated, service_role;
GRANT ALL ON TABLE public.wolffia_telemetry TO anon, authenticated, service_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;

-- 7. กำหนด Security Policy สำรอง (กรณีที่ Supabase เปิด RLS ไว้อัตโนมัติ)
DROP POLICY IF EXISTS "Allow anon all on sensor_readings" ON public.sensor_readings;
CREATE POLICY "Allow anon all on sensor_readings" ON public.sensor_readings 
FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow anon all on wolffia_telemetry" ON public.wolffia_telemetry;
CREATE POLICY "Allow anon all on wolffia_telemetry" ON public.wolffia_telemetry 
FOR ALL TO anon, authenticated USING (true) WITH CHECK (true);

